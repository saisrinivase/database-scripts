SELECT
    'CAP-001',
    'Capacity',
    'HIGH',
    CASE
        WHEN c.usage_pct >= 95 THEN 'FAIL'
        WHEN c.usage_pct >= 85 THEN 'WARN'
        ELSE 'PASS'
    END,
    CASE
        WHEN c.usage_pct >= 85 THEN 1
        ELSE 0
    END,
    'Connection usage warn >= 85%, fail >= 95%',
    'current=' || c.current_connections
    || ' max=' || c.max_connections
    || ' usage_pct=' || c.usage_pct,
    'Use connection pooling, tune app concurrency, or increase max_connections only with memory planning.'
FROM (
    WITH raw AS (
        SELECT
            (SELECT count(*) FROM pg_stat_activity)::numeric AS current_connections,
            (SELECT setting::numeric FROM pg_settings WHERE name = 'max_connections') AS max_connections
    )
    SELECT
        current_connections,
        max_connections,
        round(100.0 * current_connections / NULLIF(max_connections, 0), 2) AS usage_pct
    FROM raw
) AS c

