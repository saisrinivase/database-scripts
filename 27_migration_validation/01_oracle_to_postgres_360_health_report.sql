SELECT
    'OBJ-003',
    'Schema Design',
    'HIGH',
    CASE WHEN f.issue_count = 0 THEN 'PASS' ELSE 'WARN' END,
    f.issue_count,
    'Foreign keys should have supporting indexes on referencing columns',
    CASE
        WHEN f.issue_count = 0 THEN 'All FKs have supporting indexes'
        ELSE 'sample=' || f.sample_fk
    END,
    'Create indexes on FK referencing columns to avoid parent UPDATE/DELETE slowdowns.'
FROM (
    WITH fk AS (
        SELECT
            c.oid AS constraint_oid,
            c.conname,
            c.conrelid,
            c.conkey,
            n.nspname AS schema_name,
            t.relname AS table_name
        FROM pg_constraint c
        JOIN pg_class t
            ON t.oid = c.conrelid
        JOIN pg_namespace n
            ON n.oid = t.relnamespace
        WHERE c.contype = 'f'
          AND n.nspname !~ '^pg_'
          AND n.nspname <> 'information_schema'
    ),
    missing AS (
        SELECT
            fk.schema_name,
            fk.table_name,
            fk.conname
        FROM fk
        WHERE NOT EXISTS (
            SELECT 1
            FROM pg_index i
            WHERE i.indrelid = fk.conrelid
              AND i.indisvalid
              AND i.indisready
              AND (
                  SELECT array_agg(k.attnum ORDER BY k.ord)
                  FROM unnest(i.indkey::smallint[]) WITH ORDINALITY AS k(attnum, ord)
                  WHERE k.ord <= array_length(fk.conkey, 1)
              ) = fk.conkey
        )
    )
    SELECT
        count(*)::bigint AS issue_count,
        COALESCE(
            (
                SELECT string_agg(format('%I.%I(%I)', schema_name, table_name, conname), ', ')
                FROM (
                    SELECT schema_name, table_name, conname
                    FROM missing
