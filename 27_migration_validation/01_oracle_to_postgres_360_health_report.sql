SELECT
    'VAC-001',
    'Vacuum and Bloat',
    'HIGH',
    CASE WHEN v.issue_count = 0 THEN 'PASS' ELSE 'WARN' END,
    v.issue_count,
    'Dead tuple pressure: table >= 100MB and dead_tuple_pct >= 20%',
    CASE
        WHEN v.issue_count = 0 THEN 'No high dead tuple tables'
        ELSE 'sample=' || v.sample_tables
    END,
    'Tune autovacuum thresholds/frequency and run targeted VACUUM (ANALYZE) on hot tables.'
FROM (
    WITH table_stats AS (
        SELECT
            s.schemaname,
            s.relname,
            s.n_live_tup,
            s.n_dead_tup,
            pg_total_relation_size(s.relid) AS total_bytes,
            round(100.0 * s.n_dead_tup / NULLIF(s.n_live_tup + s.n_dead_tup, 0), 2) AS dead_tuple_pct
        FROM pg_stat_user_tables s
    ),
    pressure AS (
        SELECT
            schemaname,
            relname,
            dead_tuple_pct
        FROM table_stats
        WHERE total_bytes >= 100::bigint * 1024 * 1024
          AND n_dead_tup >= 10000
          AND dead_tuple_pct >= 20
    )
    SELECT
        count(*)::bigint AS issue_count,
        COALESCE(
            (
                SELECT string_agg(format('%I.%I(%s%%)', schemaname, relname, dead_tuple_pct), ', ')
                FROM (
                    SELECT schemaname, relname, dead_tuple_pct
                    FROM pressure
                    ORDER BY dead_tuple_pct DESC
                    LIMIT 5
                ) AS t
            ),
            'none'
        ) AS sample_tables
    FROM pressure
) AS v

