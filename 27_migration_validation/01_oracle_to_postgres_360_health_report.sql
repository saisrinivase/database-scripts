SELECT
    'IO-001',
    'I/O and Cache',
    'MEDIUM',
    CASE WHEN io.cache_hit_ratio >= 0.95 THEN 'PASS' ELSE 'WARN' END,
    CASE WHEN io.cache_hit_ratio >= 0.95 THEN 0 ELSE 1 END,
    'Global cache hit ratio should be >= 95%',
    'cache_hit_ratio=' || round(io.cache_hit_ratio::numeric, 4),
    'Investigate index/query patterns and memory sizing (shared_buffers/effective_cache_size).'
FROM (
    WITH agg AS (
        SELECT
            COALESCE(sum(blks_hit), 0)::numeric AS blks_hit,
            COALESCE(sum(blks_read), 0)::numeric AS blks_read
        FROM pg_stat_database
        WHERE datname NOT IN ('template0', 'template1')
    )
    SELECT
        COALESCE(blks_hit / NULLIF(blks_hit + blks_read, 0), 1.0) AS cache_hit_ratio
    FROM agg
) AS io

UNION ALL

SELECT
    'WAL-001',
    'WAL and Checkpoints',
    'MEDIUM',
    CASE WHEN w.issue_count = 0 THEN 'PASS' ELSE 'WARN' END,
    w.issue_count,
    'Recommended baseline: max_wal_size >= 4GB, checkpoint_timeout >= 10min, checkpoint_completion_target >= 0.90',
    w.evidence,
    'Tune WAL/checkpoint settings based on write rate and storage throughput.'
FROM (
    WITH raw AS (
        SELECT
            (SELECT setting::numeric FROM pg_settings WHERE name = 'max_wal_size') AS max_wal_size_value,
            (SELECT unit FROM pg_settings WHERE name = 'max_wal_size') AS max_wal_size_unit,
            (SELECT setting::numeric FROM pg_settings WHERE name = 'checkpoint_timeout') AS checkpoint_timeout_value,
            (SELECT unit FROM pg_settings WHERE name = 'checkpoint_timeout') AS checkpoint_timeout_unit,
            (SELECT setting::numeric FROM pg_settings WHERE name = 'checkpoint_completion_target') AS checkpoint_completion_target
    ),
    normalized AS (
        SELECT
            CASE
                WHEN max_wal_size_unit = 'kB' THEN max_wal_size_value * 1024
                WHEN max_wal_size_unit = '8kB' THEN max_wal_size_value * 8192
